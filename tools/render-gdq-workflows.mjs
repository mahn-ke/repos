import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { resolve, dirname } from 'node:path';
import { generatedFiles } from './generated-config.mjs';

const repository = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const target = resolve(repository, '../gdqreminder-by-vincent/.github/workflows');
const moduleDirectory = resolve(repository, 'infrastructure/modules/general');
const moduleText = readFileSync(`${moduleDirectory}/main.tf`, 'utf8');
const header = moduleText.match(/default\s*=\s*<<EOT\n([\s\S]*?)\nEOT/)?.[1];
if (!header) throw new Error('Could not resolve the generator header');

for (const name of ['deploy', 'automerge', 'infrastructure-review', 'plan-comment']) {
  let content = readFileSync(`${moduleDirectory}/src/.github/workflows/${name}.yml`, 'utf8');
  if (name === 'deploy') {
    content = content.replace('# GDQ_REVIEW_INPUTS', '    with:\n      infrastructure_review: true');
  }
  const expected = `${header}\n\n${content}`;
  const output = `${target}/autogenerated-${name}.yml`;
  if (process.argv.includes('--check')) {
    if (readFileSync(output, 'utf8') !== expected) throw new Error(`${name} wrapper differs from its generator`);
  } else writeFileSync(output, expected);
}
console.log(process.argv.includes('--check') ? 'GDQ workflows match generator sources' : 'Regenerated GDQ workflows');

const reporter = `${header}\n\n${readFileSync(`${moduleDirectory}/src/.github/workflows/plan-comment.yml`, 'utf8')}`;
const localReporter = `${repository}/.github/workflows/autogenerated-plan-comment.yml`;
if (process.argv.includes('--check')) {
  if (readFileSync(localReporter, 'utf8') !== reporter) throw new Error('Repos plan reporter differs from its generator');
} else writeFileSync(localReporter, reporter);

const manifestPath = `${repository}/tools/gdq-generated-files.json`;
const manifest = `${JSON.stringify(generatedFiles(repository), null, 2)}\n`;
if (process.argv.includes('--check')) {
  if (readFileSync(manifestPath, 'utf8') !== manifest) throw new Error('Trusted GDQ manifest differs from generator templates');
} else writeFileSync(manifestPath, manifest);